#!/usr/bin/env python3
"""Assemble RESULTS.md from the release tooling, so every printed number is regenerated.

    python scripts/make_results.py            # writes RESULTS.md (several minutes)
    python scripts/make_results.py --fast     # fewer bootstrap draws, for a smoke test

Runs, in order: ``python -m crossmep results`` for the benchmark and train splits
of the current data revision and the benchmark of the earlier ones,
``verify/compare_gaps.py`` (current revision and 3.0), ``verify/tier_trends.py``,
``verify/compare_sections.py --sensitivity``, ``verify/compare_composition.py``
and ``verify/catalog_stress.py``, and writes their outputs under fixed headings.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from crossmep import __version__  # noqa: E402
from crossmep.io import DATA_VERSION, DATA_VERSIONS  # noqa: E402


def run(args):
    r = subprocess.run([sys.executable, *args], cwd=ROOT, capture_output=True, text=True, check=True)
    return r.stdout.rstrip()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--out", default=os.path.join(ROOT, "RESULTS.md"))
    a = ap.parse_args(argv)
    boot = ["--n-boot", "200"] if a.fast else []
    older = [v for v in DATA_VERSIONS if v != DATA_VERSION]
    paper = DATA_VERSIONS[-1]

    L = [f"# Results for the public release (release {__version__})", "",
         f"Generated by `python scripts/make_results.py`: `python -m crossmep results` (benchmark and train, revision "
         f"{DATA_VERSION}; benchmark, revisions {', '.join(older)}), `python verify/compare_gaps.py` (revisions {DATA_VERSION} and "
         f"{paper}), `python verify/tier_trends.py`, `python verify/compare_sections.py --sensitivity`, "
         "`python verify/compare_composition.py` and `python verify/catalog_stress.py`; regenerate after any change. "
         "These are the authoritative values for the public files (README, \"Versions and relation to the paper\").", ""]
    L += [run(["-m", "crossmep", "results", "--split", "benchmark"]), "",
          run(["-m", "crossmep", "results", "--split", "train"]), ""]
    for v in older:
        L += [run(["-m", "crossmep", "results", "--split", "benchmark", "--version", v]), ""]

    L += [f"## Clear-gap distribution vs. the June 2026 Duplex samples (paper section 5.2 as published)", "",
          f"`python verify/compare_gaps.py` (revision {DATA_VERSION}) and `--version {paper}`: Wasserstein-1 distances of the "
          "generated gap distribution to the June 2026 duplex samples the gap lognormal was fitted to (`verify/measured_gaps*.json`); "
          "the generated side uses every neighbour gap of the benchmark. Definitions: `verify/VERIFICATION.md`.", "",
          "```", run(["verify/compare_gaps.py"]), "```", "",
          "```", run(["verify/compare_gaps.py", "--version", paper]), "```", ""]

    L += ["## Tier trends with intervals (paper section 5.1)", "",
          f"`python verify/tier_trends.py`: per-tier medians of the benchmark (revision {DATA_VERSION}) with bootstrap intervals, "
          "Spearman rank correlations with the tier, and a population estimate from freshly generated contexts.", "",
          "```", run(["verify/tier_trends.py", *(["--per-tier", "400", "--n-boot", "300"] if a.fast else [])]), "```", ""]

    L += ["## Clear gaps on sections of two open buildings (paper section 5.2)", "",
          "`python verify/compare_sections.py --sensitivity`: pipe-pipe gaps between bare surfaces, measured on sections every "
          "250 mm through the buildingSMART Duplex Apartment and Medical-Dental Clinic models (CC BY 4.0; `verify/measured/`), "
          f"against the benchmark of revision {DATA_VERSION}. The gap lognormal was fitted on the duplex; the clinic is held out. "
          "Definitions and the June 2026 measurement: `verify/VERIFICATION.md`.", "",
          "```", run(["verify/compare_sections.py", "--sensitivity", *boot, *(["--n-floor", "100"] if a.fast else [])]), "```", ""]

    L += ["## What a hanger carries: composition on sections of two open buildings", "",
          "`python verify/compare_composition.py`: bundles at hanger locations (sections every 250 mm) through the merged "
          "disciplines of each open building, against the benchmark contexts made of the same kinds. Kind shares, kind mixing "
          "and row stacking are compared conditional on the element count; pipe sizes by nearest DN of the generator's series. "
          f"The composition parameters of revision {DATA_VERSION} were adjusted after this comparison was first run on revision 4.0, "
          "so for the current files it is in sample (a design check); the electrical share and the mounting surface are not "
          "testable on these models (`VERIFICATION_LOG.md` section 6).", "",
          "```", run(["verify/compare_composition.py", *boot]), "```", ""]

    L += ["## Catalog stress test (paper section 5.3)", "",
          f"`python verify/catalog_stress.py`: the paper's illustrative two-size clamp catalog on the benchmark (revision {DATA_VERSION}) "
          "with cluster-bootstrap intervals, every released split, a Monte Carlo population estimate, sensitivity to the "
          "attach-diameter rule and bin tolerance, and the demand curve of best-placed sizes.", "",
          "```", run(["verify/catalog_stress.py", *boot, *(["--mc-per-tier", "200"] if a.fast else [])]), "```", ""]

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L).rstrip() + "\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
